#!/usr/bin/env python3
"""Watch Bridge rebrand (life-stuff#98).

Generates flavor-only string overrides: for every app/src/main/res/values*/strings.xml,
each <string> whose text contains "Gadgetbridge" is copied to
app/src/watchbridge/res/<same dir>/strings_wb_rebrand.xml with "Gadgetbridge" -> "Watch Bridge".
Upstream files are never edited, so `git merge upstream/master` stays clean.
Re-run after every upstream merge. Exit 1 if nothing was generated (sanity).
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "app/src/main/res"
DST = ROOT / "app/src/watchbridge/res"
OUT_NAME = "strings_wb_rebrand.xml"
OLD, NEW = "Gadgetbridge", "Watch Bridge"
NAME_RE = re.compile(r"(?:(?<=\\n)|(?<![/@.A-Za-z0-9_-]))Gadgetbridge(?![A-Za-z0-9_/-]|\.[A-Za-z0-9])")  # ASCII-only guards: skip URLs/paths/ids, keep Korean suffixes
# strings that name real files/DB tables called "Gadgetbridge" — renaming the text would mislead
SKIP = {"activity_db_management_import_export_explanation"}
STRING_RE = re.compile(r'<string\s+name="([^"]+)"([^>]*)>(.*?)</string>', re.S)

total_files = total_strings = 0
for src in sorted(SRC.glob("values*/strings.xml")):
    text = src.read_text(encoding="utf-8")
    items = []
    for m in STRING_RE.finditer(text):
        name, attrs, body = m.group(1), m.group(2), m.group(3)
        if name in SKIP:
            continue
        new_body = NAME_RE.sub(NEW, body)
        if new_body != body:
            items.append(f'    <string name="{name}"{attrs}>{new_body}</string>')
    out = DST / src.parent.name / OUT_NAME
    if items:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text('<?xml version="1.0" encoding="utf-8"?>\n'
                       '<!-- GENERATED by tools/wb_rebrand.py — do not edit by hand -->\n'
                       '<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="MissingTranslation,ExtraTranslation">\n'
                       + "\n".join(items) + "\n</resources>\n", encoding="utf-8")
        total_files += 1
        total_strings += len(items)
    elif out.exists():
        out.unlink()
print(f"rebrand: {total_strings} strings in {total_files} locale files")
sys.exit(0 if total_strings else 1)
